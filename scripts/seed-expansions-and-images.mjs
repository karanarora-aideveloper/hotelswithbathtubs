async function run() {
  console.log('Connecting to MongoDB...');
  await mongoose.connect(process.env.MONGODB_URI);
  const collection = mongoose.connection.collection('hotels');

  console.log(`Starting upload and database seeding for ${NEW_HOTELS.length} verified stays...`);

  for (const h of NEW_HOTELS) {
    const { rawImage, imageKey, ...hotelData } = h;

    // 1. Upload optimized WebP to R2
    const cdnImageUrl = await uploadToR2(rawImage, imageKey);

    // 2. Prepare full document
    const doc = {
      ...hotelData,
      image: cdnImageUrl,
      images: [cdnImageUrl],
      verified: true,
      crossVerified: true,
      crossVerifiedAt: new Date(),
      crossVerifiedSources: ['Booking.com', 'Agoda'],
      bathtubConfirmed: true,
      createdAt: new Date(),
      updatedAt: new Date(),
    };

    // 3. Upsert into MongoDB
    await collection.updateOne(
      { slug: doc.slug },
      { $set: doc },
      { upsert: true }
    );
    console.log(`✅ Upserted ${doc.name} (${doc.city}, ${doc.country}) -> ${doc.price}`);
  }

  console.log(`\n🎉 All ${NEW_HOTELS.length} hotels successfully processed, uploaded to R2, and seeded to MongoDB.`);
  await mongoose.disconnect();
}

run().catch(console.error);
