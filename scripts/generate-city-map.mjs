import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

function slugify(text) {
  if (!text) return '';
  return text
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim()
    .replace(/&+/g, 'and')
    .replace(/['’]/g, '')
    .replace(/[^\w\s-]/g, '')
    .replace(/[\s_-]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

const countryMap = {
  'usa': 'usa',
  'united states': 'usa',
  'united kingdom': 'uk',
  'uk': 'uk',
  'india': 'india',
  'united arab emirates': 'uae',
  'uae': 'uae',
};

export const CITY_ALIASES = {
  'bengaluru': { city: 'bangalore', country: 'india' },
  'gurugram': { city: 'gurgaon', country: 'india' },
  'bombay': { city: 'mumbai', country: 'india' },
  'calcutta': { city: 'kolkata', country: 'india' },
  'madras': { city: 'chennai', country: 'india' },
  'trivandrum': { city: 'thiruvananthapuram', country: 'india' },
  'cochin': { city: 'kochi', country: 'india' },
  'mahipalpur': { city: 'delhi', country: 'india' },
  'new-delhi': { city: 'delhi', country: 'india' },
};

const locationsPath = path.join(rootDir, 'public/locations.json');
if (!fs.existsSync(locationsPath)) {
  throw new Error('public/locations.json missing');
}

const locs = JSON.parse(fs.readFileSync(locationsPath, 'utf8'));
const map = {};

for (const [country, cities] of Object.entries(locs)) {
  const cSlug = countryMap[country.toLowerCase()] || slugify(country);
  for (const city of cities) {
    const s = slugify(city);
    if (s && !map[s]) {
      map[s] = cSlug;
    }
  }
}

// Add aliases to naked city map
for (const [alias, target] of Object.entries(CITY_ALIASES)) {
  if (!map[alias]) {
    map[alias] = target.country;
  }
}

const code = `// Auto-generated by scripts/generate-city-map.mjs from public/locations.json
export const cityToCountry: Record<string, string> = ${JSON.stringify(map, null, 2)};

export const CITY_COUNTRY_MAP: Record<string, string> = cityToCountry;

export const CITY_ALIASES: Record<string, { city: string; country: string }> = ${JSON.stringify(CITY_ALIASES, null, 2)};
`;

fs.writeFileSync(path.join(rootDir, 'functions/cityMap.ts'), code, 'utf8');
console.log(`✅ Generated functions/cityMap.ts with ${Object.keys(map).length} city slugs.`);
