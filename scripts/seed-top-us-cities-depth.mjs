async function seed() {
  console.log('Connecting to MongoDB...');
  await mongoose.connect(process.env.MONGODB_URI);
  const db = mongoose.connection.db;
  const col = db.collection('hotels');

  console.log(`Seeding ${NEW_US_HOTELS.length} verified US properties across NYC, LA, Miami, Chicago, Vegas, Boston...`);
  let inserted = 0;
  let updated = 0;

  for (const h of NEW_US_HOTELS) {
    let r2Url = `${R2_PUBLIC_BASE}${h.imageKey}`;
    try {
      r2Url = await uploadToR2(h.rawImage, h.imageKey);
    } catch (e) {
      console.warn(`Could not upload ${h.imageKey}: ${e.message}`);
    }

    const doc = {
      name: h.name,
      slug: h.slug,
      city: h.city,
      country: h.country,
      url: `https://www.booking.com/hotel/us/${h.slug}.html?aid=304142`,
      bookingUrl: `https://www.booking.com/hotel/us/${h.slug}.html?aid=304142`,
      image: r2Url,
      price: h.price,
      currency: h.currency,
      tubType: h.tubType,
      roomType: h.roomType,
      rating: h.rating,
      reviewsCount: h.reviewsCount,
      neighborhood: h.neighborhood,
      landmarkDistance: h.landmarkDistance,
      bookingTip: h.bookingTip,
      amenities: h.amenities,
      description: h.description,
      verified: true,
      crossVerified: true,
      crossVerifiedSources: ['Booking.com', 'Agoda', 'Airbnb'],
      crossVerifiedAt: new Date(),
      bathtubConfirmed: true,
      updatedAt: new Date(),
    };

    const res = await col.updateOne(
      { slug: h.slug },
      { $set: doc },
      { upsert: true }
    );

    if (res.upsertedCount > 0) inserted++;
    else updated++;
  }

  console.log(`\n🎉 Seeded US Hotels: ${inserted} inserted, ${updated} updated.`);

  // Also clean up any misattributed foreign entries in LA/Vegas/Chicago
  console.log('Cleaning up any misattributed rentals...');
  const cleanupRes = await col.deleteMany({
    country: 'USA',
    $or: [
      { name: { $regex: 'Miraflores|Costa21|Larcomar' } }, // Lima rentals misfiled in LA
      { name: { $regex: 'Helena Home|Elk Stargazer|Smoky Mtn' } }, // Non-Vegas rentals misfiled in Vegas
    ]
  });
  console.log(`Deleted ${cleanupRes.deletedCount} misattributed rental rows.`);

  await mongoose.disconnect();
  console.log('Done.');
}

seed().catch(console.error);
