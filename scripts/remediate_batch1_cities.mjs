async function remediateBatch1() {
  console.log('🔌 Connecting to MongoDB Atlas for Batch 1 Remediation...');
  await mongoose.connect(process.env.MONGODB_URI);
  const col = mongoose.connection.collection('hotels');

  console.log(`Applying precision updates to ${HOTEL_UPDATES.length} hotels in Batch 1...`);
  let updatedCount = 0;

  for (const h of HOTEL_UPDATES) {
    const { _id, ...fields } = h;
    const filter = { _id: new mongoose.Types.ObjectId(_id) };
    const res = await col.updateOne(filter, { $set: fields });
    if (res.matchedCount > 0) {
      updatedCount++;
      console.log(`✅ [${updatedCount}/${HOTEL_UPDATES.length}] Updated: "${fields.name}" (${fields.city})`);
    } else {
      console.warn(`⚠️ ID not matched in DB: ${_id} ("${fields.name}")`);
    }
  }

  console.log(`\nUpserting ${UDAIPUR_UPSERTS.length} iconic Udaipur luxury flagships...`);
  for (const u of UDAIPUR_UPSERTS) {
    const filter = { name: u.name, city: u.city };
    const res = await col.updateOne(filter, { $set: u }, { upsert: true });
    console.log(`🌟 Upserted: "${u.name}" (${u.city}) - matched: ${res.matchedCount}, upsertedId: ${res.upsertedId || 'Existing'}`);
  }

  const finalTotal = await col.countDocuments({});
  console.log(`\n🎉 BATCH 1 REMEDIATION COMPLETE! Total hotels in DB: ${finalTotal}`);

  await mongoose.disconnect();
}

